-- Один активный тренер — одна строка членства в инстансе группы.
-- Расчёт ЗП суммирует занятия тренера по КАЖДОЙ его строке в инстансе, поэтому вторая
-- активная строка = двойная оплата (кейс июнь-2026: Виолетта, строки «суша»+«вода»).
-- Работа «суша+вода» оплачивается отметкой ДВУХ занятий в group_sessions (75к каждое),
-- а не второй строкой членства. Если понадобятся разные ставки за сушу/воду — снять
-- индекс и добавить role-атрибуцию занятий (см. беклог №17, подгруппы Арт-свим).
CREATE UNIQUE INDEX IF NOT EXISTS trainer_groups_one_active_per_instance
  ON trainer_groups (trainer_id, group_instance_id)
  WHERE subscription_end IS NULL AND group_instance_id IS NOT NULL;
